-- Demonstrates real app-style INSERT, SELECT, UPDATE and DELETE against the demo group.
-- The surrounding transaction is rolled back so this file is repeatable and leaves no demo edits behind.
BEGIN;

DO $$
DECLARE expense_id uuid; settlement_id uuid; demo_amount numeric; admin_balance numeric; member_balance numeric;
BEGIN
  SELECT balance INTO admin_balance FROM get_group_balances('20000000-0000-4000-8000-000000000001') WHERE user_id='00000000-0000-4000-8000-000000000001';
  SELECT balance INTO member_balance FROM get_group_balances('20000000-0000-4000-8000-000000000001') WHERE user_id='00000000-0000-4000-8000-000000000002';
  demo_amount:=abs(coalesce(admin_balance,0))+abs(coalesce(member_balance,0))+12.00;
  expense_id:=add_expense_with_splits(
    '20000000-0000-4000-8000-000000000001',
    '00000000-0000-4000-8000-000000000001',
    'DML demo shared expense',demo_amount,
    (SELECT id FROM categories WHERE name='Food'),'exact',
    jsonb_build_array(jsonb_build_object('user_id','00000000-0000-4000-8000-000000000002','share_amount',demo_amount))
  );
  RAISE NOTICE 'Inserted expense %',expense_id;
  UPDATE expenses SET notes='Updated through db/dml_demo.sql' WHERE id=expense_id;
  PERFORM 1 FROM expenses WHERE id=expense_id AND notes='Updated through db/dml_demo.sql';
  settlement_id:=settle_up(
    '20000000-0000-4000-8000-000000000001',
    '00000000-0000-4000-8000-000000000002',
    '00000000-0000-4000-8000-000000000001',12.00,'DML demo payment'
  );
  UPDATE settlements SET note='Updated demo payment note' WHERE id=settlement_id;
  RAISE NOTICE 'Inserted and updated settlement %',settlement_id;
  DELETE FROM settlements WHERE id=settlement_id;
  DELETE FROM expenses WHERE id=expense_id;
END $$;

-- SELECT reads the seeded app data and reports audit events generated by the demo statements.
SELECT group_name,title,payer_name,amount,split_count FROM v_expense_details
WHERE group_id='20000000-0000-4000-8000-000000000001' ORDER BY expense_date DESC LIMIT 5;
SELECT table_name,operation,count(*) AS writes FROM audit_log
WHERE changed_at>=transaction_timestamp() GROUP BY table_name,operation ORDER BY table_name,operation;
ROLLBACK;
